/**
 * hero-poster.js — shared "poster -> live scene" handshake of the above-the-fold WebGL heroes (Home, About, Services); ONE definition for all three.
 * The page ships a static POSTER (webp, frame 0 of the scene, `<img data-hero-poster>` inside the scene host, reserved size, in the first paint with the text).
 * The live three.js scene is imported later (idle); it builds, compiles shaders and renders FRAME 0 to a still invisible canvas, then waits for the page to be fully loaded
 * (window load + fonts ready, capped at 15 s so a stalled resource never keeps the poster forever), renders frame 0 again on the final layout and calls revealLive():
 * the canvas replaces the poster in one frame (no fade). The scene clock starts at 0 at that moment => the animation begins from the poster's state; the poster itself is rendered per viewport-width bucket and pixel-ratio class so it matches the live frame (tools/gen-posters.cjs).
 * No WebGL / any failure: nothing is revealed, the poster stays as the fallback. prefers-reduced-motion: the scene shows frame 0 and never starts its clock.
 * Posters are generated by tools/gen-posters.cjs (npm run poster); the hand-over is checked frame by frame by tools/poster-swap-gate.cjs (npm run audit:poster).
 */
const LOAD_CAP = 15000;
let loaded = null;

/** fonts.ready can resolve BEFORE the text asks for its faces (nothing loading yet): wait again while the set is loading */
const fontsDone = async () => {
  if (!document.fonts) return;
  for (let i = 0; i < 6; i++) { await document.fonts.ready; await new Promise((r) => requestAnimationFrame(r)); if (document.fonts.status === 'loaded') break; }
};

/** the hero's own finite animations (title word reveal, fades): the Home fit reads the title's line rects, which MOVE while they play */
const heroSettled = () => {
  const run = (n) => {
    const anims = (document.querySelector('.hero')?.getAnimations({ subtree: true }) || []).filter((a) => a.playState === 'running' && a.effect?.getComputedTiming().iterations !== Infinity);
    if (!anims.length || n > 4) return null;
    return Promise.allSettled(anims.map((a) => a.finished)).then(() => new Promise((r) => requestAnimationFrame(r))).then(() => run(n + 1));
  };
  return Promise.race([run(0), new Promise((r) => setTimeout(r, 3000))]);
};

/** resolves when window load, fonts and the hero's reveal animations are done (then two frames, so the final layout is painted) */
export const whenPageLoaded = () => loaded ||= Promise.race([
  Promise.all([
    document.readyState === 'complete' ? null : new Promise((r) => addEventListener('load', r, { once: true })),
    fontsDone(),
  ]).then(() => new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)))).then(heroSettled),
  new Promise((r) => setTimeout(r, LOAD_CAP)),
]).then(() => new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r))));

export const posterOf = (host) => host.querySelector('[data-hero-poster]');

/** the live canvas takes over in ONE frame: `.is-ready` shows the canvas and the poster is hidden in the same task (no opacity transition, no blend). The poster is the same picture at exactly the same box as the canvas (tools/gen-posters.cjs, geometry checked by tools/poster-swap-gate.cjs), so nothing moves. */
export function revealLive(host, canvas) {
  const poster = posterOf(host);
  canvas.classList.add('is-ready');
  if (poster) poster.hidden = true;
}
